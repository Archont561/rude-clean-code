"""Guard the published, wheel-only developer sandbox and automation entry points."""

import os
import re
import tomllib
from pathlib import Path
from types import ModuleType

from automation.lib import activate


def test_published_bundle_matches_workflow_and_uses_wheels(repo_root: Path) -> None:
    config = tomllib.loads((repo_root / "pixi-sandbox.toml").read_text())
    bundles = {bundle["name"]: bundle for bundle in config["bundle"]}
    assert config["cargo_vendor"] is False
    assert bundles["developer"]["environments"] == ["default"]
    assert bundles["developer"]["platforms"] == ["linux-64"]

    workflow = (repo_root / ".github/workflows/pixi-sandbox.yml").read_text()
    assert "--envs default" in workflow
    assert "--branch sandbox/developer-linux-64" in workflow
    assert "--cargo-vendor false" in workflow

    lock_path = repo_root / "pixi.lock"
    if lock_path.exists():
        lock = lock_path.read_text()
        section = re.search(
            r"(?ms)^  default:\n(.*?)(?=^  [^ ]+:\n|^packages:\n)", lock
        )
        assert section is not None
        assert "      linux-64:" in section.group(1)
        locations = re.findall(r"^      - pypi: (.+)$", section.group(1), re.MULTILINE)
        assert locations
        assert all(location.endswith(".whl") for location in locations)


def test_scripts_dir_contains_only_restore_script(repo_root: Path) -> None:
    entries = [p.name for p in (repo_root / "scripts").iterdir()]
    assert entries == ["restore.sh"]
    restore = (repo_root / "scripts/restore.sh").read_text()
    assert "Generated by pixi-sandbox init" in restore
    assert "pixi-sandbox-version:" in restore
    assert "DEFAULT_BRANCH=sandbox/developer-linux-64" in restore
    assert "CONFIG=$ROOT/pixi-sandbox.toml" in restore


def test_pixi_manifest_uses_automation_lib_activate_and_tools_task(
    repo_root: Path, dodo_module: ModuleType
) -> None:
    manifest = tomllib.loads((repo_root / "pixi.toml").read_text())
    dependencies = manifest["pypi-dependencies"]
    assert "rude-clean-code" not in dependencies
    assert "hatchling" in dependencies
    assert "doit" in dependencies
    assert manifest["tasks"]["tools"] == "doit"
    assert "automation/lib/activate.py" in manifest["activation"]["env"]["PYTHONPATH"]

    install_cmd = dodo_module.task_install_projects()["actions"][0]
    assert "--no-build-isolation" in install_cmd
    assert "--no-deps" in install_cmd
    assert install_cmd[-1] == "./rude-clean-code"
    for task_fn in (dodo_module.task_test, dodo_module.task_coverage):
        task = task_fn()
        assert "install-projects" in task["task_dep"]
        for action in task["actions"]:
            assert not any("PYTHONPATH=" in part for part in action)


def test_activate_discovers_package_src_without_duplicates(repo_root: Path) -> None:
    src_path = str(repo_root / "rude-clean-code" / "src")
    computed = activate.python_path(repo_root, f"{src_path}{os.pathsep}/extra/path")
    parts = computed.split(os.pathsep)
    assert parts[0] == src_path
    assert parts.count(src_path) == 1
    assert "/extra/path" in parts
