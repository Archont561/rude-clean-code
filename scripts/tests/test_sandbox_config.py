"""Guard the published, wheel-only developer sandbox."""

import importlib.util
import re
import tomllib
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[2]


def _load_dodo() -> ModuleType:
    spec = importlib.util.spec_from_file_location("dodo", ROOT / "dodo.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_published_bundle_matches_workflow_and_uses_wheels():
    config = tomllib.loads((ROOT / "pixi-sandbox.toml").read_text())
    bundles = {bundle["name"]: bundle for bundle in config["bundle"]}
    assert config["cargo_vendor"] is False
    assert bundles["developer"]["environments"] == ["default"]
    assert bundles["developer"]["platforms"] == ["linux-64"]

    workflow = (ROOT / ".github/workflows/pixi-sandbox.yml").read_text()
    assert "--envs default" in workflow
    assert "--branch sandbox/developer-linux-64" in workflow
    assert "--cargo-vendor false" in workflow

    lock_path = ROOT / "pixi.lock"
    if lock_path.exists():
        lock = lock_path.read_text()
        # Pixi v7 lists environment selections before top-level package metadata.
        section = re.search(
            r"(?ms)^  default:\n(.*?)(?=^  [^ ]+:\n|^packages:\n)", lock
        )
        assert section is not None
        assert "      linux-64:" in section.group(1)
        locations = re.findall(r"^      - pypi: (.+)$", section.group(1), re.MULTILINE)
        assert locations
        assert all(location.endswith(".whl") for location in locations)


def test_restore_script_is_the_generated_one_for_this_bundle():
    restore = (ROOT / "scripts/restore.sh").read_text()
    assert "Generated by pixi-sandbox init" in restore
    assert "pixi-sandbox-version:" in restore
    assert "DEFAULT_BRANCH=sandbox/developer-linux-64" in restore
    assert "CONFIG=$ROOT/pixi-sandbox.toml" in restore


def test_package_tests_install_local_projects_without_editable_lock_entries():
    manifest = tomllib.loads((ROOT / "pixi.toml").read_text())
    dependencies = manifest["pypi-dependencies"]
    assert "rude-clean-code" not in dependencies
    assert "hatchling" in dependencies
    assert "doit" in dependencies
    assert "scripts/activate.py" in manifest["activation"]["env"]["PYTHONPATH"]

    dodo = _load_dodo()
    install_cmd = dodo.task_install_projects()["actions"][0]
    assert "--no-build-isolation" in install_cmd
    assert "--no-deps" in install_cmd
    assert install_cmd[-1] == "."
    for task_fn in (dodo.task_test, dodo.task_coverage):
        task = task_fn()
        assert "install-projects" in task["task_dep"]
        for action in task["actions"]:
            assert not any("PYTHONPATH=" in part for part in action)
